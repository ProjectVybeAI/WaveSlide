"""docs/EVALUATION.md: the report as a document, one section per BRIEF §11 test.

A report that includes synthetic sessions says so in its first lines and on every section, so
no synthetic number can be mistaken for a measurement on people.
"""

from app.contract.evaluation import ConfusionMatrix, E1GestureAccuracy, EvaluationReport

NOT_RECORDED = {
    "E1": "no gesture sessions",
    "E2": "no finger-count labels",
    "E3": "no talking sessions",
    "E4": "no commands fired",
    "E5": "no gesture sessions with a distance",
    "E6": "no gesture sessions with a lighting level",
    "E7": "no gesture sessions",
    "E8": "no ratings in eval/feedback.csv yet",
    "Ablation": "no talking sessions",
}


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1%}"


def _confusion(cm: ConfusionMatrix) -> str:
    rows = [[label, *map(str, counts)] for label, counts in zip(cm.labels, cm.matrix, strict=True)]
    return _table(["shown \\ recognised", *cm.labels], rows)


def _e1_table(e1: E1GestureAccuracy) -> str:
    people = sorted({p for row in e1.rows for p in row.per_participant})
    rows = []
    for r in e1.rows:
        cells = [
            f"{t.correct}/{t.total}" if (t := r.per_participant.get(person)) else "-" for person in people
        ]
        rows.append([r.gesture, r.action, *cells, f"{r.correct}/{r.total} ({_pct(r.accuracy)})"])
    return _table(["Gesture", "Action", *people, "All"], rows)


def render(report: EvaluationReport, chart_dir: str = "eval") -> str:
    s = report.sections
    mark = " (SYNTHETIC)" if report.synthetic else ""
    parts = [
        "# WaveSlide: Evaluation results",
        f"Run `{report.id}` on {report.created_at[:10]}. Sources: {', '.join(report.sources)}. "
        f"{report.n_sessions} sessions, participants {', '.join(report.participants)}. "
        "Generated by `npm run eval`; do not edit by hand.",
    ]
    if report.synthetic:
        parts.append(
            "> **SYNTHETIC DATA.** These sessions are generated landmarks (`npm run seed`), not people. "
            "They prove the harness works end to end and are not a measurement of WaveSlide. Real "
            "numbers come from `eval/PROTOCOL.md` recordings (`npm run eval` without `--sources synthetic`)."
        )

    def section(code: str, title: str, body: str | None, chart: str | None = None, note: str = "") -> None:
        parts.append(f"## {code}  {title}{mark}")
        if body is None:
            parts.append(f"_Not recorded: {NOT_RECORDED[code]}._")
            return
        if report.synthetic:
            parts.append("_Computed from synthetic sessions._")
        parts.append(body)
        if chart:
            parts.append(f"![{title}]({chart_dir}/{chart})")
        if note:
            parts.append(note)

    e1 = s.e1_gestures
    section(
        "E1",
        "Per-gesture accuracy by participant",
        e1 and _e1_table(e1),
        "e1_gestures.png",
        "A segment is correct when exactly the mapped command fires from its start to 0.5 s after its end.",
    )

    e2 = s.e2_finger_count
    section(
        "E2",
        "Finger-count jumps (1-5 one hand, 6-10 two hands)",
        e2
        and f"Accuracy {_pct(e2.accuracy)}.\n\nOne hand:\n\n{_confusion(e2.one_hand)}"
        + (f"\n\nTwo hands:\n\n{_confusion(e2.two_hand)}" if e2.two_hand else ""),
        "e2_finger_count.png",
    )

    e3 = s.e3_false_triggers
    section(
        "E3",
        "False triggers per minute while talking",
        e3
        and f"{e3.minutes} minutes of talking. Active: **{e3.active_per_min:.2f}/min**. "
        f"Paused: **{e3.paused_per_min:.2f}/min**.\n\n"
        + _table(
            ["Participant", "Active per minute"], [[p, f"{v:.2f}"] for p, v in e3.per_participant.items()]
        ),
        "e3_false_triggers.png",
    )

    e4 = s.e4_response_time
    section(
        "E4",
        "Response time",
        e4
        and _table(
            ["Measure", "Value"],
            [
                ["Commands measured", str(e4.n_commands)],
                [
                    "Pipeline p50 / p95 (frame handed over to key sent, after landmarks)",
                    f"{e4.pipeline_p50_ms:.2f} ms / {e4.pipeline_p95_ms:.2f} ms",
                ],
                [
                    "Swipe: end of motion to command, p50 (negative: fires before the arm stops)",
                    "n/a"
                    if e4.gesture_end_to_command_p50_ms is None
                    else f"{e4.gesture_end_to_command_p50_ms:.0f} ms",
                ],
                [
                    "Key to practice-deck render, p50 (live use)",
                    "n/a" if e4.key_to_render_p50_ms is None else f"{e4.key_to_render_p50_ms:.0f} ms",
                ],
            ],
        ),
        "e4_latency.png",
        "Camera exposure and MediaPipe time are outside this number (ARCHITECTURE.md, limitations).",
    )

    for code, title, data, chart in (
        ("E5", "Accuracy and detection rate by distance", s.e5_distance, "e5_distance.png"),
        ("E6", "Accuracy and detection rate by lighting", s.e6_lighting, "e6_lighting.png"),
    ):
        section(
            code,
            title,
            data
            and _table(
                ["Condition", "Rules", "Random forest", "Hand detected", "Mean luminance"],
                [
                    [
                        r.condition,
                        _pct(r.rules_accuracy),
                        _pct(r.ml_accuracy),
                        _pct(r.detection_rate),
                        "n/a" if r.luminance_mean is None else f"{r.luminance_mean:.0f}",
                    ]
                    for r in data.rows
                ],
            ),
            chart,
        )

    e7 = s.e7_rules_vs_model
    section(
        "E7",
        "Rules against random forest (leave-one-participant-out)",
        e7
        and _table(
            ["Recogniser", "Macro-F1", "Time per frame"],
            [["Rules", f"{e7.rules.macro_f1:.3f}", f"{e7.rules.ms_per_frame:.3f} ms"]]
            + ([["Random forest", f"{e7.ml.macro_f1:.3f}", f"{e7.ml.ms_per_frame:.3f} ms"]] if e7.ml else []),
        )
        + f"\n\nRules:\n\n{_confusion(e7.rules.confusion)}"
        + (f"\n\nRandom forest:\n\n{_confusion(e7.ml.confusion)}" if e7.ml else ""),
        "e7_rules_vs_model.png",
    )

    e8 = s.e8_ratings
    section(
        "E8",
        "User ratings",
        e8
        and f"Ease {e8.ease_mean:.2f} / 5, reliability {e8.reliability_mean:.2f} / 5.\n\n"
        + _table(
            ["Participant", "Ease", "Reliability", "Comment"],
            [[r.participant, str(r.ease), str(r.reliability), r.comment] for r in e8.rows],
        ),
    )

    ab = s.ablation
    section(
        "Ablation",
        "What each reliability control prevents",
        ab
        and f"{ab.minutes} minutes of talking, engine active, one control off at a time.\n\n"
        + _table(
            ["Control off", "False triggers per minute"],
            [[r.control.replace("_", " "), f"{r.false_triggers_per_min:.2f}"] for r in ab.rows],
        ),
        "ablation.png",
        "Hold and stillness stop false starts. Cooldown and re-arm stop repeats of a deliberate gesture, "
        "so on talking (no deliberate gestures) they have nothing to prevent and show no change.",
    )
    return "\n\n".join(parts) + "\n"
